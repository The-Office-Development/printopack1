/* Printopack System - Arabic for the admin dashboard.
   Loaded before admin.js. The dictionary is keyed by the exact English string used in the
   interface, so a screen that has never been translated still renders in English rather
   than breaking. Nothing here touches the CONTENT being edited: every record keeps its own
   English and Arabic fields, and this file only translates the dashboard around them.
   {x} placeholders are filled by T() and may carry HTML; word order differs between the two
   languages, which is exactly why they are placeholders rather than concatenation. */
/* Arabic agrees the noun with the number in four bands, where English has only singular and
   plural: one, two (a dual form of its own), three to ten, and eleven upwards. "1 change" and
   "3 changes" cannot both be built by adding an s to a stem, so every counted phrase that a
   person actually reads is written out in all four rather than interpolated. */
function arCount(n,one,two,few,many){
 n=Number(n)||0;
 if(n===1)return one;
 if(n===2)return two;
 var r=n%100;
 if(r>=3&&r<=10)return String(few).split('{n}').join(n);
 return String(many).split('{n}').join(n);
}
